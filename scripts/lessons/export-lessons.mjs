#!/usr/bin/env node
// Exports active lessons into files other code reviewers already read.
//
// Usage:
//   node scripts/lessons/export-lessons.mjs [--repo <dir>] [--lessons <dir>] [--copilot-cap 4000]
//
// Targets, in the repo root (default: git toplevel of the cwd):
//   REVIEW.md                         read by Anthropic managed review; indexed by CodeRabbit/Greptile
//   .github/copilot-instructions.md   read by Copilot code review (first 4,000 characters only)
//
// Each target gets one generated block between
//   <!-- dtk:lessons:start -->  and  <!-- dtk:lessons:end -->
// Only that block is rewritten; every byte outside the markers is kept. A file without
// markers gets the block appended; a missing file is created. With nothing active to
// export, a missing or marker-less file is left alone (an existing block is still refreshed). Lessons are ordered by severity, then path, so a run with the same
// lessons writes the same bytes (idempotent: the second run leaves no diff).
//
// Copilot cap: the whole copilot-instructions.md file is kept at <= --copilot-cap
// characters (default 4000, Copilot's read limit). Lessons are added in severity order
// until the next one would cross the cap; the rest are summarized in one
// "…and N more in docs/lessons/" line. Text outside the markers is never trimmed: if it
// alone leaves no room, the block shrinks to that pointer line and a warning is printed.
//
// Exit: 0 ok, 1 bad usage, 2 malformed markers (nothing written).

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { bySeverityThenPath, listLessons, repoRoot } from './lessons-lib.mjs';

const START = '<!-- dtk:lessons:start -->';
const END = '<!-- dtk:lessons:end -->';

function parseArgs(argv) {
  const opts = { repo: null, lessons: null, copilotCap: 4000 };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--repo') opts.repo = argv[++i];
    else if (a === '--lessons') opts.lessons = argv[++i];
    else if (a === '--copilot-cap') opts.copilotCap = Number(argv[++i]);
    else { console.error(`Unknown option: ${a}`); process.exit(1); }
  }
  if (!Number.isInteger(opts.copilotCap) || opts.copilotCap <= 0) {
    console.error('--copilot-cap must be a positive integer'); process.exit(1);
  }
  return opts;
}

const len = (s) => [...s].length; // characters (code points), not bytes
const clean = (s) => s.replace(/\s+/g, ' ').replace(/<!--/g, '&lt;!--').trim();

function lessonLine(l, withPath) {
  const sev = l.severity ? `[${clean(l.severity)}] ` : '';
  const rule = l.rule ? ` — ${clean(l.rule)}` : '';
  const path = withPath ? ` (\`docs/lessons/${l.rel}\`)` : '';
  return `- **${sev}${clean(l.title)}**${rule}${path}`;
}

function block(lines, more) {
  const out = [
    START,
    '## Lessons from past reviews',
    '',
    'Generated by dtk from `docs/lessons/` (active lessons only). Edit the lesson files, not this block.',
    '',
  ];
  if (lines.length === 0 && more === 0) out.push('No active lessons yet.');
  out.push(...lines);
  if (more > 0) out.push(`- …and ${more} more in \`docs/lessons/\`.`);
  out.push(END);
  return out.join('\n');
}

// Split an existing file around its markers; null when there are none.
function split(text, file) {
  const s = text.indexOf(START);
  const e = text.indexOf(END);
  if (s === -1 && e === -1) return null;
  const malformed = s === -1 || e === -1 || e < s
    || text.indexOf(START, s + 1) !== -1 || text.indexOf(END, e + 1) !== -1;
  if (malformed) {
    console.error(`${file}: malformed ${START} / ${END} markers; fix them by hand. Nothing written.`);
    process.exit(2);
  }
  return { before: text.slice(0, s), after: text.slice(e + END.length) };
}

function plan(file, lessons, withPath, cap) {
  const exists = existsSync(file);
  const text = exists ? readFileSync(file, 'utf8') : '';
  const parts = split(text, file);
  // Nothing to export and no block of ours to refresh: leave the file (or its absence) alone.
  if (!parts && lessons.length === 0) return { file, action: 'skipped (no active lessons)' };
  const wrap = (b) => {
    if (parts) return parts.before + b + parts.after;
    if (!exists || text === '') return b + '\n';
    return text + (text.endsWith('\n') ? '\n' : '\n\n') + b + '\n';
  };
  const lines = lessons.map((l) => lessonLine(l, withPath));
  let k = lines.length;
  let next = wrap(block(lines, 0));
  let warning = null;
  if (cap) {
    while (k > 0 && len(next) > cap) {
      k--;
      next = wrap(block(lines.slice(0, k), lines.length - k));
    }
    if (len(next) > cap) warning = `${file}: text outside the markers leaves no room under ${cap} chars (file is ${len(next)})`;
  }
  const action = !exists ? 'created' : next === text ? 'unchanged' : 'updated';
  return { file, next, action, count: k, total: lines.length, warning };
}

const opts = parseArgs(process.argv.slice(2));
const repo = resolve(opts.repo || repoRoot());
const lessonsDir = resolve(opts.lessons || join(repo, 'docs/lessons'));
const active = listLessons(lessonsDir).filter((l) => l.status === 'active').sort(bySeverityThenPath);

// Plan both targets first so a malformed file aborts before anything is written.
const plans = [
  plan(join(repo, 'REVIEW.md'), active, true, null),
  plan(join(repo, '.github/copilot-instructions.md'), active, false, opts.copilotCap),
];
for (const p of plans) {
  if (p.next !== undefined && p.action !== 'unchanged') {
    mkdirSync(dirname(p.file), { recursive: true });
    writeFileSync(p.file, p.next);
  }
  const n = p.count === undefined ? '' : ` (${p.count}/${p.total} lessons)`;
  console.log(`${p.file.slice(repo.length + 1)}: ${p.action}${n}`);
  if (p.warning) console.error(`warning: ${p.warning}`);
}
